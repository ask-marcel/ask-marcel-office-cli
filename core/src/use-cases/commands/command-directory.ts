/*
 * The static command-to-package directory (docs/plans/2026-10-01-package-split.md,
 * "Cross-package names"): which package of the split holds each command. Core
 * reads it without a registry, so every package can tell a caller where a command
 * it does not have lives, and a guard can check that a command reference names the
 * package that holds it. `command-directory.test.ts` keeps it true to the registry.
 *
 * The commands every package has (`docs`, `help`, `help-json`, `mcp`) are not
 * in it: no package sends a caller elsewhere for them.
 */

